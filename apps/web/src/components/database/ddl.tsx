export type Dialect = "postgres" | "mysql";
export const dialectOf = (s: DatabaseSchema): Dialect =>
	s.engine === "postgres" ? "postgres" : "mysql";

/** One identifier, quoted so any name stays one name. */
export const quote = (d: Dialect, name: string) =>
	d === "postgres"
		? `"${name.replaceAll('"', '""')}"`
		: `\`${name.replaceAll("`", "``")}\``;
const qualified = (d: Dialect, schema: string, name: string) =>
	`${quote(d, schema)}.${quote(d, name)}`;

/** A droppable thing in the tree. */
export type DbObject =
	| { kind: "table"; schema: string; name: string; table: DbTable["kind"] }
	| { kind: "enum"; schema: string; name: string }
	| { kind: "sequence"; schema: string; name: string }
	| { kind: "routine"; schema: string; name: string; routine: DbRoutine };

const TABLE_NOUN: Record<DbTable["kind"], string> = {
	table: "table",
	view: "view",
	materialized_view: "materialized view",
	foreign_table: "foreign table",
	collection: "collection",
};

export const objectNoun = (o: DbObject) =>
	o.kind === "table"
		? TABLE_NOUN[o.table]
		: o.kind === "routine"
			? o.routine.kind
			: o.kind === "enum"
				? "enum"
				: "sequence";

export function dropSql(d: Dialect, o: DbObject): string {
	const name = qualified(d, o.schema, o.name);
	if (o.kind === "enum") return `drop type ${name};`;
	if (o.kind === "routine")
		// Postgres overloads routines, so its argument types name one.
		return d === "postgres"
			? `drop ${o.routine.kind} ${name}(${o.routine.arguments});`
			: `drop ${o.routine.kind} ${name};`;
	return `drop ${objectNoun(o)} ${name};`;
}

export type Template = "view" | "enum" | "function" | "schema";

/** A ready-to-edit statement for the SQL editor. */
export function templateSql(d: Dialect, t: Template, schema: string): string {
	const q = (name: string) => qualified(d, schema, name);
	switch (t) {
		case "schema":
			return `create schema ${quote(d, "new_schema")};`;
		case "view":
			return `create view ${q("new_view")} as\nselect 1 as id;`;
		case "enum":
			return `create type ${q("new_enum")} as enum ('draft', 'active', 'archived');`;
		case "function":
			return d === "postgres"
				? `create function ${q("new_function")}(a integer)\nreturns integer\nlanguage sql\nas $$\n  select a + 1\n$$;`
				: `create function ${q("new_function")}(a int)\nreturns int deterministic\nreturn a + 1;`;
	}
}

/** The api's refusal of a write the member has no grant for. */
const isForbidden = (e: unknown) => e instanceof ApiError && e.status === 403;
const errorText = (e: unknown) =>
	e instanceof Error ? e.message : "Something went wrong.";


/** The default a new key column gets: Postgres identity, MySQL auto_increment. */
const AUTO: Record<Dialect, string> = {
	postgres: "identity",
	mysql: "auto_increment",
};

type Column = {
	key: number;
	name: string;
	type: string;
	nullable: boolean;
	default: string;
	primaryKey: boolean;
};

export function createTableSql(
	d: Dialect,
	schema: string,
	name: string,
	columns: Column[],
): string {
	const keys = columns.filter((c) => c.primaryKey);
	const lines = columns.map((c) => {
		const parts = [quote(d, c.name.trim()), c.type.trim()];
		const auto = c.default.trim().toLowerCase() === AUTO[d];
		if (!c.nullable || c.primaryKey) parts.push("not null");
		if (auto)
			parts.push(
				d === "postgres"
					? "generated by default as identity"
					: "auto_increment",
			);
		else if (c.default.trim()) parts.push(`default ${c.default.trim()}`);
		return `  ${parts.join(" ")}`;
	});
	if (keys.length)
		lines.push(
			`  primary key (${keys.map((c) => quote(d, c.name.trim())).join(", ")})`,
		);
	return `create table ${qualified(d, schema, name.trim())} (\n${lines.join(",\n")}\n);`;
}

function columnErrors(columns: Column[]) {
	const seen = new Set<string>();
	return columns.map((c) => {
		const name = c.name.trim();
		const e: { name?: string; type?: string } = {};
		if (!name) e.name = "Name it";
		else if (seen.has(name)) e.name = "Already used";
		seen.add(name);
		if (!c.type.trim()) e.type = "Pick a type";
		return e;
	});
}

/** Columns, then the CREATE TABLE it makes, then create; on success the new table opens. */
export function NewTableDialog({
	open,
	onOpenChange,
	serviceId,
	database,
	dialect,
	schema,
	existing,
	onCreated,
	onForbidden,
}: {
	open: boolean;
	onOpenChange: (open: boolean) => void;
	serviceId: string;
	database?: string;
	dialect: Dialect;
	schema: string;
	/** Names already taken in the schema. */
	existing: string[];
	onCreated: (name: string) => void;
	onForbidden: () => void;
}) {
	const uid = useId();
	const qc = useQueryClient();
	const first = (): Column[] => [
		{
			key: 0,
			name: "id",
			type: "bigint",
			nullable: false,
			default: AUTO[dialect],
			primaryKey: true,
		},
		{
			key: 1,
			name: "",
			type: "text",
			nullable: true,
			default: "",
			primaryKey: false,
		},
	];
	const [step, setStep] = useState<"columns" | "review">("columns");
	// The columns step slides back in only after the review was shown, not on open.
	const [moved, setMoved] = useState(false);
	// A column added from the button takes the focus, so typing goes on from the keyboard.
	const [added, setAdded] = useState<number | null>(null);
	const [name, setName] = useState("");
	const [columns, setColumns] = useState<Column[]>(first);
	const [attempted, setAttempted] = useState(false);
	const [pending, setPending] = useState(false);
	const [failure, setFailure] = useState<string | null>(null);

	const reset = () => {
		setStep("columns");
		setMoved(false);
		setName("");
		setColumns(first());
		setAttempted(false);
		setFailure(null);
	};
	const close = (o: boolean) => {
		if (pending) return;
		onOpenChange(o);
		if (!o) reset();
	};

	const nameError = !name.trim()
		? "Name the table"
		: existing.includes(name.trim())
			? `${schema} already has ${name.trim()}`
			: undefined;
	const errors = columnErrors(columns);
	const valid =
		!nameError && columns.length > 0 && errors.every((e) => !e.name && !e.type);
	const sql = createTableSql(dialect, schema, name, columns);
	const patch = (key: number, next: Partial<Column>) =>
		setColumns((cs) => cs.map((c) => (c.key === key ? { ...c, ...next } : c)));

	function review(e: FormEvent) {
		e.preventDefault();
		setAttempted(true);
		if (!valid) {
			(
				document.querySelector(
					`[data-new-table="${uid}"] [aria-invalid=true]`,
				) as HTMLElement | null
			)?.focus();
			return;
		}
		setFailure(null);
		setMoved(true);
		setStep("review");
	}

	async function create() {
		setPending(true);
		setFailure(null);
		try {
			const result = await databaseApi.query(serviceId, {
				sql,
				readOnly: false,
				database,
			});
			if (result.error) {
				setFailure(result.error.message);
				return;
			}
			await qc.invalidateQueries({ queryKey: ["database", serviceId] });
			toast.success(`Created ${schema}.${name.trim()}`);
			onCreated(name.trim());
			onOpenChange(false);
			reset();
		} catch (e) {
			if (isForbidden(e)) {
				onForbidden();
				setFailure("Creating tables needs write access to this service.");
			} else setFailure(errorText(e));
		} finally {
			setPending(false);
		}
	}

	const typesId = `${uid}-types`;
	return (
		<Dialog open={open} onOpenChange={close}>
			<DialogContent className="sm:max-w-2xl" data-new-table={uid}>
				<DialogHeader>
					<DialogTitle>New table in {schema}</DialogTitle>
					<DialogDescription>
						{step === "columns"
							? "Step 1 of 2: name the table and its columns."
							: "Step 2 of 2: this is the statement that runs."}
					</DialogDescription>
				</DialogHeader>
				{step === "columns" ? (
					<form
						id={`${uid}-form`}
						onSubmit={review}
						noValidate
						className={cn("grid min-w-0 gap-5", moved && "t-page")}
						style={{ "--dir": -1 } as CSSProperties}
					>
						<Field
							id={`${uid}-name`}
							label="Table name"
							error={attempted ? nameError : undefined}
						>
							<Input
								id={`${uid}-name`}
								value={name}
								onChange={(e) => setName(e.target.value)}
								placeholder="orders"
								autoComplete="off"
								spellCheck={false}
								autoFocus
								aria-invalid={(attempted && !!nameError) || undefined}
								aria-describedby={`${uid}-name-msg`}
							/>
						</Field>
						<fieldset className="grid min-w-0 gap-2">
							<legend className="mb-2 text-sm font-medium">Columns</legend>
							<datalist id={typesId}>
								{TYPES[dialect].map((t) => (
									<option key={t} value={t} />
								))}
							</datalist>
							<div
								className="hidden grid-cols-[minmax(0,1.2fr)_minmax(0,1fr)_minmax(0,1fr)_3rem_3rem_2rem] gap-2 px-0.5 text-xs text-muted-foreground sm:grid"
								aria-hidden
							>
								<span>Name</span>
								<span>Type</span>
								<span>Default</span>
								<span className="text-center">Null</span>
								<span className="text-center">Key</span>
								<span />
							</div>
							<ul className="grid max-h-[min(22rem,45dvh)] gap-2 overflow-y-auto p-0.5">
								{columns.map((c, i) => {
									const e = attempted ? errors[i] : undefined;
									const label = c.name.trim() || `column ${i + 1}`;
									return (
										<li
											key={c.key}
											className="grid grid-cols-2 items-start gap-2 rounded-lg bg-muted/50 p-2 sm:grid-cols-[minmax(0,1.2fr)_minmax(0,1fr)_minmax(0,1fr)_3rem_3rem_2rem] sm:bg-transparent sm:p-0"
										>
											<div className="col-span-2 sm:col-span-1">
												<Input
													value={c.name}
													onChange={(ev) =>
														patch(c.key, { name: ev.target.value })
													}
													placeholder="name"
													autoFocus={c.key === added}
													aria-label={`Name of ${label}`}
													aria-invalid={!!e?.name || undefined}
													title={e?.name}
													spellCheck={false}
													autoComplete="off"
													className="h-8"
												/>
											</div>
											<Input
												value={c.type}
												onChange={(ev) =>
													patch(c.key, { type: ev.target.value })
												}
												list={typesId}
												placeholder="type"
												aria-label={`Type of ${label}`}
												aria-invalid={!!e?.type || undefined}
												title={e?.type}
												spellCheck={false}
												autoComplete="off"
												className="h-8"
											/>
											<Input
												value={c.default}
												onChange={(ev) =>
													patch(c.key, { default: ev.target.value })
												}
												placeholder={c.primaryKey ? AUTO[dialect] : "none"}
												aria-label={`Default of ${label}, as SQL`}
												spellCheck={false}
												autoComplete="off"
												className="h-8"
											/>
											<label
												htmlFor={`${uid}-null-${c.key}`}
												className="flex h-8 items-center gap-2 text-xs sm:justify-center"
											>
												<Checkbox
													id={`${uid}-null-${c.key}`}
													checked={c.nullable && !c.primaryKey}
													disabled={c.primaryKey}
													onCheckedChange={(v) =>
														patch(c.key, { nullable: v === true })
													}
													aria-label={`${label} can be null`}
												/>
												<span className="sm:sr-only">Null</span>
											</label>
											<label
												htmlFor={`${uid}-pk-${c.key}`}
												className="flex h-8 items-center gap-2 text-xs sm:justify-center"
											>
												<Checkbox
													id={`${uid}-pk-${c.key}`}
													checked={c.primaryKey}
													onCheckedChange={(v) =>
														patch(c.key, { primaryKey: v === true })
													}
													aria-label={`${label} is part of the primary key`}
												/>
												<span className="sm:sr-only">Primary key</span>
											</label>
											<Button
												type="button"
												variant="ghost"
												size="icon-sm"
												className="justify-self-end text-muted-foreground"
												disabled={columns.length === 1}
												onClick={() =>
													setColumns((cs) => cs.filter((x) => x.key !== c.key))
												}
												aria-label={`Remove ${label}`}
											>
												<X />
											</Button>
										</li>
									);
								})}
							</ul>
							<Button
								type="button"
								variant="ghost"
								size="sm"
								className="justify-self-start text-muted-foreground"
								onClick={() => {
									const key = Math.max(-1, ...columns.map((c) => c.key)) + 1;
									setAdded(key);
									setColumns((cs) => [
										...cs,
										{
											key,
											name: "",
											type: "text",
											nullable: true,
											default: "",
											primaryKey: false,
										},
									]);
								}}
							>
								<Plus data-icon="inline-start" />
								Add column
							</Button>
							<p className="text-xs text-muted-foreground">
								Defaults are SQL: <code>now()</code>, <code>'draft'</code>,{" "}
								<code>0</code>. <code>{AUTO[dialect]}</code> numbers rows on its
								own.
							</p>
						</fieldset>
					</form>
				) : (
					<div
						className="grid min-w-0 gap-3 t-page"
						style={{ "--dir": 1 } as CSSProperties}
					>
						<pre className="max-h-[min(24rem,50dvh)] overflow-auto rounded-lg bg-muted/60 p-4 font-mono text-xs leading-relaxed">
							{sql}
						</pre>
						{failure && (
							<p role="alert" className="t-reveal text-sm text-bad-text">
								{failure}
							</p>
						)}
					</div>
				)}
				<DialogFooter>
					{step === "columns" ? (
						<>
							<Button
								type="button"
								variant="ghost"
								onClick={() => close(false)}
							>
								Cancel
							</Button>
							<Button type="submit" form={`${uid}-form`}>
								Review
							</Button>
						</>
					) : (
						<>
							<Button
								type="button"
								variant="ghost"
								onClick={() => setStep("columns")}
								disabled={pending}
							>
								<ArrowLeft data-icon="inline-start" />
								Back
							</Button>
							<Button type="button" onClick={create} disabled={pending}>
								{pending && (
									<Loader2 className="animate-spin" data-icon="inline-start" />
								)}
								Create table
							</Button>
						</>
					)}
				</DialogFooter>
			</DialogContent>
		</Dialog>
	);
}

/** Names a new Postgres database or MySQL schema and creates it. */
export function NewDatabaseDialog({
	open,
	onOpenChange,
	serviceId,
	noun,
	onCreated,
	onForbidden,
}: {
	open: boolean;
	onOpenChange: (open: boolean) => void;
	serviceId: string;
	/** "database", or "schema" where the engine calls it that. */
	noun: string;
	onCreated: (name: string) => void;
	onForbidden: () => void;
}) {
	const uid = useId();
	const qc = useQueryClient();
	const [name, setName] = useState("");
	const [attempted, setAttempted] = useState(false);
	const [pending, setPending] = useState(false);
	const [failure, setFailure] = useState<string | null>(null);
	const parsed = DatabaseName.safeParse(name.trim());
	const error = parsed.success
		? undefined
		: name.trim()
			? (parsed.error.issues[0]?.message ?? "Not a valid name")
			: `Name the ${noun}`;
	const close = (o: boolean) => {
		if (pending) return;
		onOpenChange(o);
		if (!o) {
			setName("");
			setAttempted(false);
			setFailure(null);
		}
	};

	async function submit(e: FormEvent) {
		e.preventDefault();
		setAttempted(true);
		if (error) return;
		setPending(true);
		setFailure(null);
		try {
			await databaseApi.createDatabase(serviceId, name.trim());
			await qc.invalidateQueries({ queryKey: ["database", serviceId] });
			toast.success(`Created ${name.trim()}`);
			onCreated(name.trim());
			onOpenChange(false);
			setName("");
			setAttempted(false);
		} catch (err) {
			if (isForbidden(err)) {
				onForbidden();
				setFailure(`Creating a ${noun} needs write access to this service.`);
			} else setFailure(errorText(err));
		} finally {
			setPending(false);
		}
	}

	return (
		<Dialog open={open} onOpenChange={close}>
			<DialogContent className="sm:max-w-md">
				<form onSubmit={submit} noValidate className="grid gap-4">
					<DialogHeader>
						<DialogTitle>New {noun}</DialogTitle>
						<DialogDescription>
							An empty {noun} on the same instance, owned by the service's
							superuser.
						</DialogDescription>
					</DialogHeader>
					<Field
						id={`${uid}-db`}
						label="Name"
						error={attempted ? error : undefined}
						hint="Letters, digits, _ and -; it starts with a letter or _."
					>
						<Input
							id={`${uid}-db`}
							value={name}
							onChange={(e) => setName(e.target.value)}
							placeholder="analytics"
							autoComplete="off"
							spellCheck={false}
							autoFocus
							aria-invalid={(attempted && !!error) || undefined}
							aria-describedby={`${uid}-db-msg`}
						/>
					</Field>
					{failure && (
						<p role="alert" className="t-reveal text-sm text-bad-text">
							{failure}
						</p>
					)}
					<DialogFooter>
						<Button type="button" variant="ghost" onClick={() => close(false)}>
							Cancel
						</Button>
						<Button type="submit" disabled={pending}>
							{pending && (
								<Loader2 className="animate-spin" data-icon="inline-start" />
							)}
							Create {noun}
						</Button>
					</DialogFooter>
				</form>
			</DialogContent>
		</Dialog>
	);
}

/** Drops a whole database once its name is typed back. Needs admin. */
export function DropDatabaseDialog({
	name,
	noun,
	serviceId,
	onOpenChange,
	onDropped,
}: {
	/** The database to drop; null keeps the dialog closed. */
	name: string | null;
	noun: string;
	serviceId: string;
	onOpenChange: (open: boolean) => void;
	onDropped: (name: string) => void;
}) {
	const uid = useId();
	const qc = useQueryClient();
	const [typed, setTyped] = useState("");
	const [pending, setPending] = useState(false);
	return (
		<ConfirmDialog
			open={name !== null}
			onOpenChange={(o) => {
				if (pending) return;
				onOpenChange(o);
				if (!o) setTyped("");
			}}
			title={`Drop ${name ?? ""}?`}
			description={`Every table and row in this ${noun} is deleted, and open connections to it are closed. This can't be undone.`}
			confirmLabel={`Drop ${noun}`}
			pending={pending}
			confirmDisabled={typed !== name}
			onConfirm={async () => {
				if (!name || typed !== name) return;
				setPending(true);
				try {
					await databaseApi.dropDatabase(serviceId, name);
					toast.success(`Dropped ${name}`);
					setTyped("");
					// Leave the dropped database before refetching, so its schema never 404s on screen.
					onDropped(name);
					qc.invalidateQueries({ queryKey: ["database", serviceId] });
				} catch (e) {
					toast.error(`Couldn't drop ${name}`, {
						description: isForbidden(e)
							? `Dropping a ${noun} needs admin on this service.`
							: errorText(e),
					});
				} finally {
					setPending(false);
				}
			}}
		>
			<Field id={`${uid}-confirm`} label={`Type ${name ?? ""} to confirm`}>
				<Input
					id={`${uid}-confirm`}
					value={typed}
					onChange={(e) => setTyped(e.target.value)}
					placeholder={name ?? ""}
					autoCapitalize="none"
					spellCheck={false}
					autoComplete="off"
					className="font-mono"
				/>
			</Field>
		</ConfirmDialog>
	);
}

/** Drops one table, view, enum, sequence or routine through the query route. */
export function DropObjectDialog({
	object,
	dialect,
	serviceId,
	database,
	onOpenChange,
	onDropped,
	onForbidden,
}: {
	object: DbObject | null;
	dialect: Dialect;
	serviceId: string;
	database?: string;
	onOpenChange: (open: boolean) => void;
	onDropped: (o: DbObject) => void;
	onForbidden: () => void;
}) {
	const qc = useQueryClient();
	const [pending, setPending] = useState(false);
	const [failure, setFailure] = useState<string | null>(null);
	const sql = object ? dropSql(dialect, object) : "";
	const noun = object ? objectNoun(object) : "";
	return (
		<ConfirmDialog
			open={object !== null}
			onOpenChange={(o) => {
				if (pending) return;
				onOpenChange(o);
				if (!o) setFailure(null);
			}}
			title={`Drop ${object?.name ?? ""}?`}
			description={
				object?.kind === "table" && object.table === "table"
					? "The table and every row in it are deleted. This can't be undone."
					: `The ${noun} is deleted. Anything that depends on it makes the drop fail.`
			}
			confirmLabel={`Drop ${noun}`}
			pending={pending}
			onConfirm={async () => {
				if (!object) return;
				setPending(true);
				setFailure(null);
				try {
					const r = await databaseApi.query(serviceId, {
						sql,
						readOnly: false,
						database,
					});
					if (r.error) {
						setFailure(r.error.message);
						return;
					}
					await qc.invalidateQueries({ queryKey: ["database", serviceId] });
					toast.success(`Dropped ${object.schema}.${object.name}`);
					onDropped(object);
				} catch (e) {
					if (isForbidden(e)) {
						onForbidden();
						setFailure(
							`Dropping a ${noun} needs write access to this service.`,
						);
					} else setFailure(errorText(e));
				} finally {
					setPending(false);
				}
			}}
		>
			<pre className="overflow-x-auto rounded-lg bg-muted/60 px-3 py-2.5 font-mono text-xs">
				{sql}
			</pre>
			{failure && (
				<p role="alert" className={cn("t-reveal text-sm text-bad-text")}>
					{failure}
				</p>
			)}
		</ConfirmDialog>
	);
}

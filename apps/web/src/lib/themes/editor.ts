/*
 * Editor colour schemes people already know, each from its official light and dark
 * palette. Unlike the shadcn presets they also recolour the status vocabulary, the
 * terminal and the log viewer, so a deploy log reads like the editor does.
 */
import type { ThemeSource, Tokens } from "./types";

type Palette = {
	/** Content, chrome (sidebar, logs), raised (cards, popovers), hover and inputs. */
	bg: string;
	chrome: string;
	raised: string;
	hover: string;
	line: string;
	fg: string;
	dim: string;
	accent: string;
	ok: string;
	busy: string;
	info: string;
	warn: string;
	bad: string;
	idle: string;
	/** black, red, green, yellow, blue, magenta, cyan, white, then bright black and bright white. */
	ansi: [
		string,
		string,
		string,
		string,
		string,
		string,
		string,
		string,
		string,
		string,
	];
};

function variant(p: Palette): Tokens {
	const [k, r, g, y, b, m, c, w, bk, bw] = p.ansi;
	const ansi = [k, r, g, y, b, m, c, w, bk, r, g, y, b, m, c, bw];
	return {
		background: p.bg,
		foreground: p.fg,
		card: p.raised,
		"card-foreground": p.fg,
		popover: p.raised,
		"popover-foreground": p.fg,
		primary: p.accent,
		"primary-foreground": p.bg,
		secondary: p.hover,
		"secondary-foreground": p.fg,
		muted: p.hover,
		"muted-foreground": p.dim,
		accent: p.hover,
		"accent-foreground": p.fg,
		destructive: p.bad,
		border: p.line,
		input: p.line,
		ring: p.accent,
		brand: p.accent,
		"brand-foreground": p.bg,
		sidebar: p.chrome,
		"sidebar-foreground": p.fg,
		"sidebar-primary": p.accent,
		"sidebar-primary-foreground": p.bg,
		"sidebar-accent": p.hover,
		"sidebar-accent-foreground": p.fg,
		"sidebar-border": p.line,
		"sidebar-ring": p.accent,
		ok: p.ok,
		"ok-text": p.ok,
		busy: p.busy,
		"busy-text": p.busy,
		info: p.info,
		"info-text": p.info,
		warn: p.warn,
		"warn-text": p.warn,
		bad: p.bad,
		"bad-text": p.bad,
		idle: p.idle,
		"idle-text": p.dim,
		"log-bg": p.chrome,
		"log-fg": p.fg,
		"log-muted": p.ansi[8],
		"log-selection": `${p.accent}40`,
		...Object.fromEntries(ansi.map((v, i) => [`ansi-${i}`, v])),
	};
}

const theme = (
	id: string,
	label: string,
	light: Palette,
	dark: Palette,
): ThemeSource => ({
	id,
	label,
	group: "Editor classics",
	light: variant(light),
	dark: variant(dark),
});

